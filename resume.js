const resumeLanguage = new URLSearchParams(location.search).get("lang") === "en" ? "en" : "zh";
const resume = resumes[resumeLanguage];
document.documentElement.lang = resumeLanguage === "zh" ? "zh-CN" : "en";
document.title = resume.title;
document.querySelector("#resume-name").textContent = resume.name;
const actions = document.querySelector("#resume-actions");
actions.setAttribute("aria-label", resume.nav);
actions.querySelectorAll("a[lang]").forEach((link) => {
  if (link.lang === document.documentElement.lang) link.setAttribute("aria-current", "page");
  else link.removeAttribute("aria-current");
});
const back = document.querySelector("#resume-back");
back.textContent = resume.back;
back.href = resumeLanguage === "zh" ? "./#contact" : "./?lang=en#contact";
const pdf = document.querySelector("#resume-pdf");
pdf.href = `resume-${resumeLanguage}.pdf`;
pdf.textContent = resume.pdf;
document.querySelector("#resume-body").innerHTML = resume.sections.map(([heading, entries]) => `
  <section>
    <h2>${heading}</h2>
    ${entries.map(([label, date, bullets]) => `
      <article>
        <h3>${label}</h3>
        ${date ? `<p>${date}</p>` : ""}
        ${bullets ? `<ul>${bullets.map((item) => `<li>${item}</li>`).join("")}</ul>` : ""}
      </article>`).join("")}
  </section>`).join("");
